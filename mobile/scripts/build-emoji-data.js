'use strict';
// Builds mobile/lib/emojiData.ts, the emoji picker's offline data (2.27.1), from
// emojibase-data (MIT; see THIRD_PARTY_NOTICES.md). Nothing is fetched at run
// time and the package is not a dependency: fetch it once, outside the repo,
// then point this script at it:
//   npm pack emojibase-data@17.0.0   (in an empty folder outside the repo)
//   tar -xzf emojibase-data-17.0.0.tgz
//   node scripts/build-emoji-data.js <that folder>/package
// Kept: every emoji up to Emoji 15.0 (what Windows 11's Segoe UI Emoji draws),
// one per emoji (no skin tones), with its name and keywords. Dropped: the
// component group (skin tones and hair parts on their own) and the regional
// indicator letters.
const fs = require('node:fs');
const path = require('node:path');

const MAX_VERSION = 15;
// Our own names and tab icons for the emojibase groups (2 is "component").
const GROUPS = [
  [0, 'smileys', 'Smileys and emotion', '😀'],
  [1, 'people', 'People and body', '👋'],
  [3, 'animals', 'Animals and nature', '🐻'],
  [4, 'food', 'Food and drink', '🍔'],
  [5, 'travel', 'Travel and places', '✈️'],
  [6, 'activities', 'Activities', '⚽'],
  [7, 'objects', 'Objects', '💡'],
  [8, 'symbols', 'Symbols', '❤️'],
  [9, 'flags', 'Flags', '🏁'],
];

const root = process.argv[2];
if (!root) {
  console.error('usage: node scripts/build-emoji-data.js <emojibase-data package folder>');
  process.exit(2);
}
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const data = JSON.parse(fs.readFileSync(path.join(root, 'en', 'data.json'), 'utf8'));
const clean = (s) => String(s).toLowerCase().replace(/[\t\n]/g, ' ').replace(/\s+/g, ' ').trim();

const byGroup = new Map(GROUPS.map(([g]) => [g, []]));
for (const e of data.sort((a, b) => (a.order ?? 0) - (b.order ?? 0))) {
  if (!byGroup.has(e.group) || (e.version ?? 0) > MAX_VERSION) continue;
  const name = clean(e.label);
  const words = new Set(name.split(/[\s:,]+/));
  const tags = (e.tags || []).map(clean).filter((t) => t && !words.has(t));
  byGroup.get(e.group).push(`${e.emoji}\t${name}\t${[...new Set(tags)].join(' ')}`);
}

const lines = [
  `// Generated by scripts/build-emoji-data.js from emojibase-data ${pkg.version}`,
  '// (MIT licence, Copyright (c) 2017-2019 Miles Johnson; see THIRD_PARTY_NOTICES.md).',
  '// Do not edit by hand. Desktop only: imported by the emoji picker, never by the',
  '// iPhone app (the iOS marker gate checks).',
  '//',
  '// One string per group, one emoji per line: the emoji, a tab, its name, a tab,',
  '// its keywords separated by spaces.',
  '',
  'export const EMOJI_GROUPS: ReadonlyArray<{ key: string; name: string; icon: string }> = [',
  ...GROUPS.map(([, key, name, icon]) => `  { key: '${key}', name: '${name}', icon: '${icon}' },`),
  '];',
  '',
  'export const EMOJI_DATA: readonly string[] = [',
  ...GROUPS.map(([g]) => `  ${JSON.stringify(byGroup.get(g).join('\n'))},`),
  '];',
  '',
];
const out = path.join(__dirname, '..', 'lib', 'emojiData.ts');
fs.writeFileSync(out, lines.join('\n'));
const count = GROUPS.reduce((n, [g]) => n + byGroup.get(g).length, 0);
console.log(`${count} emoji in ${GROUPS.length} groups, ${fs.statSync(out).size} bytes -> ${out}`);
