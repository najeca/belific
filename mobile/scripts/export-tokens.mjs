// Writes design-tokens/ (tokens.json, tokens.css, tailwind-preset.js) from mobile/lib/tokens.ts, the one
// token source, so Landis and Proload can take the same look. Run from mobile/:
//   node scripts/export-tokens.mjs
// `build()` returns the three files as text (lib/designTokens.test.ts runs it to check that what is
// committed in design-tokens/ is current); this script writes them. Edit lib/tokens.ts, never the output.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CSS_PREFIX, accents, cssVarName, darkTokens, fontSize, fonts, lightTokens, radius, space } from '../lib/tokens.ts';

const HEADER = 'Generated by mobile/scripts/export-tokens.mjs from mobile/lib/tokens.ts. Do not edit by hand.';
const px = (n) => `${n}px`;
const kebab = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
// JSON, with every line after the first indented to sit inside the preset's object.
const fmt = (obj, indent = '      ') => JSON.stringify(obj, null, 2).split('\n').map((l, i) => (i === 0 ? l : indent + l)).join('\n');

function hexToRgba(hex, alpha) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
  return `rgba(${r},${g},${b},${alpha})`;
}

const colorBlock = (tokens, indent = '  ') => Object.entries(tokens).map(([k, v]) => `${indent}${cssVarName(k)}: ${v};`).join('\n');
const shapeBlock = () =>
  [
    ...Object.entries(radius).map(([k, v]) => `  ${CSS_PREFIX}radius-${k}: ${k === 'full' ? '999px' : px(v)};`),
    ...Object.entries(space).map(([k, v]) => `  ${CSS_PREFIX}space-${k.slice(1)}: ${px(v)};`),
    ...Object.entries(fonts).map(([k, v]) => `  ${CSS_PREFIX}font-${k}: ${v};`),
    ...Object.entries(fontSize).map(([k, v]) => `  ${CSS_PREFIX}font-size-${kebab(k)}: ${px(v)};`),
  ].join('\n');
const accentBlock = (a, soft, indent = '  ') =>
  [`${indent}${cssVarName('accent')}: ${a.accent};`, `${indent}${cssVarName('accentText')}: ${a.accentText};`, `${indent}${cssVarName('onAccent')}: ${a.onAccent};`, `${indent}${cssVarName('accentSoft')}: ${hexToRgba(a.accent, soft)};`].join('\n');

export function build() {
  const json = {
    $description: 'Quiet Function design tokens: the Ellie Planner look (docs/DESIGN_SYSTEM.md). ' + HEADER,
    color: { light: lightTokens, dark: darkTokens },
    accent: accents,
    radius,
    space,
    font: fonts,
    fontSize,
  };

  const css = [
    `/* ${HEADER} */`,
    '/* Usage: <html data-theme="light|dark|system" data-accent="belific|landis|proload">. Light is the default. */',
    ':root,',
    ':root[data-theme="light"] {',
    '  color-scheme: light;',
    colorBlock(lightTokens),
    shapeBlock(),
    '}',
    ':root[data-theme="dark"] {',
    '  color-scheme: dark;',
    colorBlock(darkTokens),
    '}',
    '@media (prefers-color-scheme: dark) {',
    '  :root[data-theme="system"] {',
    '    color-scheme: dark;',
    colorBlock(darkTokens, '    '),
    '  }',
    '}',
    '/* One accent per app. Belific is the default (the values above). */',
    ...['landis', 'proload'].flatMap((app) => [
      `:root[data-accent="${app}"] {`,
      accentBlock(accents[app].light, 0.12),
      '}',
      `:root[data-accent="${app}"][data-theme="dark"] {`,
      accentBlock(accents[app].dark, 0.16),
      '}',
      '@media (prefers-color-scheme: dark) {',
      `  :root[data-accent="${app}"][data-theme="system"] {`,
      accentBlock(accents[app].dark, 0.16, '    '),
      '  }',
      '}',
    ]),
    '',
  ].join('\n');

  const colorMap = Object.fromEntries(Object.keys(lightTokens).filter((k) => !k.startsWith('shadow')).map((k) => [kebab(k), `var(${cssVarName(k)})`]));
  const preset = `// ${HEADER}
// Tailwind preset: add it to a project's tailwind.config.js, next to design-tokens/tokens.css:
//   presets: [require('./design-tokens/tailwind-preset.js')]
// Colours are the CSS variables, so a change of theme or accent repaints without a rebuild.
module.exports = {
  darkMode: ['selector', '[data-theme="dark"]'],
  theme: {
    extend: {
      colors: ${fmt(colorMap)},
      borderRadius: ${fmt(Object.fromEntries(Object.entries(radius).map(([k, v]) => [k, k === 'full' ? '9999px' : px(v)])))},
      spacing: ${fmt(Object.fromEntries(Object.entries(space).map(([k, v]) => [k.slice(1), px(v)])))},
      fontFamily: {
        ui: [${JSON.stringify(fonts.ui)}],
        display: [${JSON.stringify(fonts.display)}],
        mono: [${JSON.stringify(fonts.mono)}],
      },
      fontSize: ${fmt(Object.fromEntries(Object.entries(fontSize).map(([k, v]) => [kebab(k), px(v)])))},
      boxShadow: {
        sm: 'var(${cssVarName('shadowSm')})',
        md: 'var(${cssVarName('shadowMd')})',
        lg: 'var(${cssVarName('shadowLg')})',
      },
    },
  },
};
`;
  return { 'tokens.json': `${JSON.stringify(json, null, 2)}\n`, 'tokens.css': css, 'tailwind-preset.js': preset };
}

const here = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(here, '..', '..', 'design-tokens');
  mkdirSync(out, { recursive: true });
  for (const [name, text] of Object.entries(build())) writeFileSync(join(out, name), text);
  console.log(`design-tokens written to ${out}`);
}
